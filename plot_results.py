"""
plot_results.py

Create publication-ready plots from the JSON files generated by eval.py.

Compatible with JSON files of the form:

{
  "meta": {...},
  "models": {
    "model-name": {
      "parameters": ...,
      "parameters_millions": ...,
      "n_layer": ...,
      "n_head": ...,
      "n_embd": ...,
      "tasks": {
        "hellaswag": {"accuracy": ..., "accuracy_norm": ...},
        "lambada": {"accuracy": ..., "perplexity": ...},
        ...
      }
    }
  }
}

Usage:
    python plot_results.py results/
    python plot_results.py results/gpt2_results.json
    python plot_results.py results/ --out plots/

The script accepts either a JSON file or a directory containing JSON files.
All models from all supplied JSON files are merged into one comparison.

Outputs:
    accuracy_comparison.png
    hellaswag_comparison.png
    lambada.png
    parameter_vs_performance.png
    architecture_depth_vs_performance.png
    architecture_width_vs_performance.png
    evaluation_time.png
    capability_profile.png
    model_summary.csv
    benchmark_summary.csv

If MSO values are later added to a model entry, e.g.
    "mso": 0.0123
or
    "representation": {"mso": 0.0123}

the script also creates:
    mso_vs_performance.png

Notes:
- Accuracy is displayed as percentages.
- Lower perplexity is better.
- Missing benchmarks are simply skipped.
- No artificial scores are invented for missing data.
"""

