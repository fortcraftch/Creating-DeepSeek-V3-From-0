def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate plots from eval.py JSON results."
    )
    parser.add_argument(
        "input",
        type=Path,
        help="JSON result file or directory containing JSON result files.",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("plots"),
        help="Output directory (default: plots).",
    )
    args = parser.parse_args()

    files = find_json_files(args.input)
    print("Input files:")
    for path in files:
        print(f"  - {path}")

    models, source_info = load_results(files)
    tasks = collect_tasks(models)
    df = make_dataframe(models)

