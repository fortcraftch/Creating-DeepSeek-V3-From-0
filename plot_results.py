def create_summary_tables(
    df: pd.DataFrame,
    tasks: list[str],
    out_dir: Path,
) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)

    model_columns = [
        "model",
        "display_name",
        "parameters_millions",
        "n_layer",
        "n_head",
        "n_embd",
        "mso",
    ]
    model_columns = [c for c in model_columns if c in df.columns]

    model_summary = df[model_columns].copy()
    model_summary.to_csv(out_dir / "model_summary.csv", index=False)

    rows = []
    for task in tasks:
        accuracy_col = f"{task}_accuracy"
        if accuracy_col in df.columns:
            for _, row in df.iterrows():
                value = row[accuracy_col]
                if pd.notna(value):
                    rows.append({
                        "model": row["model"],
                        "benchmark": task,
                        "metric": "accuracy",
                        "value": value,
                        "value_percent": value * 100,
                    })

        norm_col = f"{task}_accuracy_norm"
        if norm_col in df.columns:
            for _, row in df.iterrows():
                value = row[norm_col]
                if pd.notna(value):
                    rows.append({
                        "model": row["model"],
                        "benchmark": task,
                        "metric": "accuracy_norm",
                        "value": value,
                        "value_percent": value * 100,
                    })

        ppl_col = f"{task}_perplexity"
        if ppl_col in df.columns:
            for _, row in df.iterrows():
                value = row[ppl_col]
                if pd.notna(value):
                    rows.append({
                        "model": row["model"],
                        "benchmark": task,
                        "metric": "perplexity",
                        "value": value,
                        "value_percent": np.nan,
                    })

    benchmark_summary = pd.DataFrame(rows)
    benchmark_summary.to_csv(out_dir / "benchmark_summary.csv", index=False)

    print(f"[OK] {out_dir / 'model_summary.csv'}")
    print(f"[OK] {out_dir / 'benchmark_summary.csv'}")


