def plot_evaluation_time(
    df: pd.DataFrame,
    tasks: list[str],
    out_dir: Path,
) -> None:
    available = [
        t for t in tasks
        if f"{t}_seconds" in df.columns
        and df[f"{t}_seconds"].notna().any()
    ]

    if not available:
        return

    # Total time per model across available tasks.
    time_cols = [f"{t}_seconds" for t in available]
    total_seconds = df[time_cols].sum(axis=1, min_count=1)

    fig, ax = plt.subplots(figsize=(10, 6))
    bars = ax.bar(df["display_name"], total_seconds / 60)

    ax.set_ylabel("Evaluation time (minutes)")
    ax.set_title("Total evaluation time")
    ax.grid(axis="y", alpha=0.25)
    ax.tick_params(axis="x", rotation=25)

    for bar, value in zip(bars, total_seconds / 60):
        if pd.notna(value):
            ax.text(
                bar.get_x() + bar.get_width() / 2,
                bar.get_height(),
                f"{value:.1f}",
                ha="center",
                va="bottom",
            )

    save_figure(fig, out_dir, "evaluation_time.png")


def normalized_capability_scores(
    df: pd.DataFrame,
    group_tasks: list[str],
) -> pd.DataFrame:
    """
    Average available accuracy scores after converting them to [0, 1].

    This is a visualization aid only. It does NOT claim that benchmarks
    are statistically equivalent or equally difficult.
    """
    result = pd.DataFrame(index=df.index)

    for group, tasks in CAPABILITY_GROUPS.items():
        relevant = [t for t in tasks if t in group_tasks and f"{t}_accuracy" in df.columns]

        if not relevant:
            result[group] = np.nan
            continue

        result[group] = df[[f"{t}_accuracy" for t in relevant]].mean(axis=1, skipna=True)

    return result


def plot_capability_profile(
    df: pd.DataFrame,
    tasks: list[str],
    out_dir: Path,
) -> None:
    scores = normalized_capability_scores(df, tasks)

    if scores.empty or scores.notna().sum().sum() == 0:
        return

    # Radar chart with matplotlib's polar projection.
    categories = list(scores.columns)
    n = len(categories)
    angles = np.linspace(0, 2 * np.pi, n, endpoint=False).tolist()
    angles += angles[:1]

    fig = plt.figure(figsize=(9, 9))
    ax = fig.add_subplot(111, polar=True)

    for i, row in scores.iterrows():
        values = row.tolist()
        if all(pd.isna(v) for v in values):
            continue

        values = [
            0 if pd.isna(v) else float(v)
            for v in values
        ]
        values += values[:1]

        ax.plot(
            angles,
            np.array(values) * 100,
            linewidth=2,
            label=df.loc[i, "display_name"],
        )
        ax.fill(angles, np.array(values) * 100, alpha=0.08)

    ax.set_xticks(angles[:-1])
    ax.set_xticklabels(categories)
    ax.set_ylabel("Mean benchmark accuracy (%)", labelpad=25)
    ax.set_title(
        "Capability profile\n"
        "(visual aggregation of related benchmarks)",
        pad=25,
    )
    ax.set_ylim(0, 100)
    ax.grid(alpha=0.25)
    ax.legend(loc="upper left", bbox_to_anchor=(1.15, 1.05))

    save_figure(fig, out_dir, "capability_profile.png")


def plot_mso_vs_performance(
    df: pd.DataFrame,
    tasks: list[str],
    out_dir: Path,
) -> None:
    if "mso" not in df.columns or df["mso"].notna().sum() < 2:
        return

    available = [
        t for t in tasks
        if f"{t}_accuracy" in df.columns
        and df[f"{t}_accuracy"].notna().any()
    ]

    for task in available:
        plot = df[["display_name", "mso", f"{task}_accuracy"]].dropna()
        if len(plot) < 2:
            continue

        fig, ax = plt.subplots(figsize=(8, 6))
        ax.scatter(plot["mso"], plot[f"{task}_accuracy"] * 100, s=70)

        for _, row in plot.iterrows():
            ax.annotate(
                row["display_name"],
                (row["mso"], row[f"{task}_accuracy"] * 100),
                xytext=(5, 5),
                textcoords="offset points",
            )

        ax.set_xlabel("Mean squared overlap (MSO)")
        ax.set_ylabel("Accuracy (%)")
        ax.set_title(f"MSO vs {task_label(task)}")
        ax.grid(alpha=0.25)

        save_figure(
            fig,
            out_dir / "mso_vs_performance",
            f"{safe_filename(task)}.png",
        )


