def plot_accuracy_comparison(
    df: pd.DataFrame,
    tasks: list[str],
    out_dir: Path,
) -> None:
    available = []
    for task in tasks:
        col = f"{task}_accuracy"
        if col in df.columns and df[col].notna().any():
            available.append(task)

    if not available:
        print("[INFO] No accuracy benchmarks available.")
        return

    plot_df = df[["display_name"] + [f"{t}_accuracy" for t in available]].copy()
    plot_df = plot_df.set_index("display_name") * 100

    # Horizontal grouped bars are easier to read with many benchmarks.
    ax = plot_df.plot(kind="barh", figsize=(13, max(6, len(available) * 0.45)))
    ax.set_xlabel("Accuracy (%)")
    ax.set_ylabel("Model")
    ax.set_title("Benchmark accuracy comparison")
    ax.grid(axis="x", alpha=0.25)
    ax.legend(
        [task_label(t) for t in available],
        title="Benchmark",
        bbox_to_anchor=(1.02, 1),
        loc="upper left",
    )

    save_figure(ax.get_figure(), out_dir, "accuracy_comparison.png")


def plot_hellaswag(
    df: pd.DataFrame,
    out_dir: Path,
) -> None:
    cols = []
    labels = []

    if "hellaswag_accuracy" in df.columns:
        cols.append("hellaswag_accuracy")
        labels.append("Accuracy")

    if "hellaswag_accuracy_norm" in df.columns:
        cols.append("hellaswag_accuracy_norm")
        labels.append("Normalized accuracy")

    if not cols:
        return

    values = df[cols] * 100
    x = np.arange(len(df))
    width = 0.8 / len(cols)

    fig, ax = plt.subplots(figsize=(11, 6))

    for i, col in enumerate(cols):
        offset = (i - (len(cols) - 1) / 2) * width
        ax.bar(x + offset, values[col], width, label=labels[i])

    ax.set_xticks(x)
    ax.set_xticklabels(df["display_name"], rotation=25, ha="right")
    ax.set_ylabel("Accuracy (%)")
    ax.set_title("HellaSwag performance")
    ax.grid(axis="y", alpha=0.25)
    ax.legend()

    save_figure(fig, out_dir, "hellaswag_comparison.png")


def plot_lambada(
    df: pd.DataFrame,
    out_dir: Path,
) -> None:
    has_acc = "lambada_accuracy" in df.columns
    has_ppl = "lambada_perplexity" in df.columns

    if not has_acc and not has_ppl:
        return

    if has_acc:
        fig, ax = plt.subplots(figsize=(10, 6))
        values = df["lambada_accuracy"] * 100
        bars = ax.bar(df["display_name"], values)
        ax.set_ylabel("Accuracy (%)")
        ax.set_title("LAMBADA accuracy")
        ax.grid(axis="y", alpha=0.25)
        ax.tick_params(axis="x", rotation=25)
        for bar, value in zip(bars, values):
            if pd.notna(value):
                ax.text(
                    bar.get_x() + bar.get_width() / 2,
                    bar.get_height(),
                    f"{value:.1f}%",
                    ha="center",
                    va="bottom",
                )
        save_figure(fig, out_dir, "lambada_accuracy.png")

    if has_ppl:
        fig, ax = plt.subplots(figsize=(10, 6))
        values = df["lambada_perplexity"]
        bars = ax.bar(df["display_name"], values)
        ax.set_ylabel("Perplexity (lower is better)")
        ax.set_title("LAMBADA perplexity")
        ax.grid(axis="y", alpha=0.25)
        ax.tick_params(axis="x", rotation=25)
        for bar, value in zip(bars, values):
            if pd.notna(value):
                ax.text(
                    bar.get_x() + bar.get_width() / 2,
                    bar.get_height(),
                    f"{value:.2f}",
                    ha="center",
                    va="bottom",
                )
        save_figure(fig, out_dir, "lambada_perplexity.png")


def plot_parameter_vs_performance(
    df: pd.DataFrame,
    tasks: list[str],
    out_dir: Path,
) -> None:
    available = [
        t for t in tasks
        if f"{t}_accuracy" in df.columns
        and df[f"{t}_accuracy"].notna().any()
    ]

    if not available:
        return

    # One figure per benchmark makes the resulting figures suitable for papers.
    for task in available:
        plot = df[["display_name", "parameters_millions", f"{task}_accuracy"]].dropna()
        if len(plot) < 2:
            continue

        fig, ax = plt.subplots(figsize=(8, 6))
        ax.scatter(
            plot["parameters_millions"],
            plot[f"{task}_accuracy"] * 100,
            s=70,
        )

        for _, row in plot.iterrows():
            ax.annotate(
                row["display_name"],
                (row["parameters_millions"], row[f"{task}_accuracy"] * 100),
                xytext=(5, 5),
                textcoords="offset points",
            )

        ax.set_xlabel("Parameters (millions)")
        ax.set_ylabel("Accuracy (%)")
        ax.set_title(f"Parameters vs {task_label(task)}")
        ax.grid(alpha=0.25)

        save_figure(
            fig,
            out_dir / "parameter_vs_performance",
            f"{safe_filename(task)}.png",
        )


