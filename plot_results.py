def safe_filename(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", name)


def display_name(model_name: str) -> str:
    """Turn common technical names into nicer plot labels."""
    replacements = {
        "gpt2Base": "GPT-2 Base",
        "gpt2Deep": "GPT-2 Deep",
        "gpt2Wide": "GPT-2 Wide",
        "gpt2-base": "GPT-2 Base",
        "gpt2-deep": "GPT-2 Deep",
        "gpt2-wide": "GPT-2 Wide",
        "gpt2-large": "GPT-2 Large",
        "gpt2-medium": "GPT-2 Medium",
        "gpt2-small": "GPT-2 Small",
    }
    if model_name in replacements:
        return replacements[model_name]

    return model_name.replace("_", " ").replace("-", " ").title()


def task_label(task: str) -> str:
    return TASK_LABELS.get(task, task.replace("_", " ").title())


def fmt_params(params_m: float | None) -> str:
    if params_m is None or not np.isfinite(params_m):
        return "?"
    if params_m >= 1000:
        return f"{params_m / 1000:.2f}B"
    return f"{params_m:.0f}M"


def extract_mso(model: dict[str, Any]) -> float | None:
    """Support several future MSO layouts."""
    candidates = [
        model.get("mso"),
        model.get("MSO"),
    ]

    representation = model.get("representation")
    if isinstance(representation, dict):
        candidates.extend([
            representation.get("mso"),
            representation.get("MSO"),
        ])

    for value in candidates:
        if isinstance(value, (int, float)) and math.isfinite(float(value)):
            return float(value)

    return None


def find_json_files(input_path: Path) -> list[Path]:
    if input_path.is_file():
        if input_path.suffix.lower() != ".json":
            raise ValueError(f"Expected a JSON file: {input_path}")
        return [input_path]

    if input_path.is_dir():
        files = sorted(input_path.glob("*.json"))
        if not files:
            raise FileNotFoundError(f"No .json files found in {input_path}")
        return files

    raise FileNotFoundError(f"Path does not exist: {input_path}")


def load_results(files: list[Path]) -> tuple[dict[str, dict[str, Any]], list[dict[str, Any]]]:
    """
    Returns:
        models: merged model dictionary
        source_info: metadata for each input file
    """
    models: dict[str, dict[str, Any]] = {}
    source_info: list[dict[str, Any]] = []

    for path in files:
        with path.open("r", encoding="utf-8") as f:
            data = json.load(f)

        if "models" not in data or not isinstance(data["models"], dict):
            print(f"[WARNING] Skipping {path}: no valid 'models' object.")
            continue

        source_info.append({
            "file": str(path),
            "timestamp": data.get("meta", {}).get("timestamp"),
            "tasks": data.get("meta", {}).get("tasks", []),
        })

        for model_name, model_data in data["models"].items():
            # If a model appears in multiple files, the later file wins.
            if model_name in models:
                print(
                    f"[WARNING] Duplicate model '{model_name}'. "
                    f"Using data from {path}."
                )

            copy = dict(model_data)
            copy["_source_file"] = str(path)
            models[model_name] = copy

    if not models:
        raise ValueError("No valid models were found.")

    return models, source_info


def collect_tasks(models: dict[str, dict[str, Any]]) -> list[str]:
    tasks = set()

    for model in models.values():
        task_data = model.get("tasks", {})
        if isinstance(task_data, dict):
            tasks.update(task_data.keys())

    ordered = [t for t in TASK_ORDER if t in tasks]
    ordered.extend(sorted(tasks - set(ordered)))
    return ordered


def task_metric(task: str, result: dict[str, Any]) -> tuple[str, float] | None:
    """
    Return the preferred metric for a task.

    HellaSwag uses raw accuracy for the main benchmark comparison.
    LAMBADA uses accuracy for the accuracy comparison and perplexity separately.
    """
    if task in ACCURACY_TASKS:
        value = result.get("accuracy")
        if isinstance(value, (int, float)) and math.isfinite(float(value)):
            return "accuracy", float(value)

    if task == "lambada":
        value = result.get("accuracy")
        if isinstance(value, (int, float)) and math.isfinite(float(value)):
            return "accuracy", float(value)

    # Generic fallback for future benchmarks.
    for key in ("accuracy", "score", "f1", "exact_match"):
        value = result.get(key)
        if isinstance(value, (int, float)) and math.isfinite(float(value)):
            return key, float(value)

    return None


def make_dataframe(models: dict[str, dict[str, Any]]) -> pd.DataFrame:
    rows = []

    for name, model in models.items():
        row = {
            "model": name,
            "display_name": display_name(name),
            "parameters_millions": model.get("parameters_millions"),
            "parameters": model.get("parameters"),
            "n_layer": model.get("n_layer"),
            "n_head": model.get("n_head"),
            "n_embd": model.get("n_embd"),
            "mso": extract_mso(model),
        }

        tasks = model.get("tasks", {})
        if isinstance(tasks, dict):
            for task, result in tasks.items():
                if not isinstance(result, dict):
                    continue

                metric = task_metric(task, result)
                if metric:
                    key, value = metric
                    row[f"{task}_{key}"] = value

                if "accuracy_norm" in result:
                    value = result["accuracy_norm"]
                    if isinstance(value, (int, float)) and math.isfinite(float(value)):
                        row[f"{task}_accuracy_norm"] = float(value)

                if "perplexity" in result:
                    value = result["perplexity"]
                    if isinstance(value, (int, float)) and math.isfinite(float(value)):
                        row[f"{task}_perplexity"] = float(value)

                if "seconds" in result:
                    value = result["seconds"]
                    if isinstance(value, (int, float)) and math.isfinite(float(value)):
                        row[f"{task}_seconds"] = float(value)

                if "total" in result:
                    value = result["total"]
                    if isinstance(value, (int, float)) and math.isfinite(float(value)):
                        row[f"{task}_total"] = int(value)

        rows.append(row)

    return pd.DataFrame(rows)


def save_figure(fig: plt.Figure, out_dir: Path, filename: str) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / filename
    fig.tight_layout()
    fig.savefig(path, dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"[OK] {path}")


